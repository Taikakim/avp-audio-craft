# Owner: GHOST-NOTE (created 2026-11-03)
"""mixtape_track_pool.py -- generate the replacement track pool for the DJ mix (owner ask 2026-11-03, asleep: run unattended).

100 tracks from six models. Each = a 30 s core generated by the model (random seed / cfg / weight / prompt inside the owner's
ranges), then extended 45 s FORWARD and 45 s BACKWARD by masked inpaint on the SAME model + prompt (core stays as context),
giving one 120 s file with the core at 45-75 s. medium-base sampler: 24 steps.
Weight: adapters = set_lora_strength(w); full finetunes / soups = delta scaling base + w*(ft-base) on the DiT (w>1 extrapolates).
Full-FT weight set: ONLINE unless the EMA shadow is converged (>=3 half-lives). Prompts: ~70% training set (rarity clip index +
kimlong pool), ~30% synthetic. Output: Mantu/sa3_lora_runs/mixtape_trackpool_2026-11-03/tNNN.wav (24-bit) + cells.jsonl + run_meta.json.
GPU lock is taken per arm (released between arms so others can run). Resumable (cells.jsonl).
RUN: setsid nohup eval/mixtape_track_pool.sh &   (wrapper waits for the GPU lock)"""
import json, os, random, sys, time
os.environ.setdefault("FLASH_ATTENTION_TRITON_AMD_ENABLE", "FALSE")
import numpy as np, soundfile as sf, torch
sys.path.insert(0, "/home/kim/Projects/SAO/eval"); sys.path.insert(0, "/home/kim/Projects/SAO/control")
from forge.fullft import load_fullft, _state_dict, ema_info

RUNS = "/run/media/kim/Mantu/sa3_lora_runs"
OUT = f"{RUNS}/mixtape_trackpool_2026-11-03"
SR, STEPS, CORE, EXT = 44100, 24, 30.0, 45.0
MM = f"{RUNS}/model_matrix"
# name, kind, ckpt, weight range, cfg range, n tracks
ARMS = [
    ("soup_mean", "fullft", f"{RUNS}/fullft/fullft_soup_fp32cmp_avp_t4096_bs1_no35/soup_mean.ckpt", (0.6, 1.8), (5, 14), 17),
    ("soup_ep7_ep14", "fullft", f"{RUNS}/fullft/fullft_soup_fp32cmp_avp_t4096_bs1_no35/soup_ep7_ep14.ckpt", (0.6, 1.8), (5, 14), 17),
    ("fullft_avp_t256_ep80", "fullft", f"{RUNS}/fullft_avp_t256/epoch=80-step=46944.weights.ckpt", (0.6, 1.8), (5, 14), 17),   # ep46 is not on disk
    ("goa5k_dora_3e-3_3033st", "adapter", f"{RUNS}/goa5k_fullft_avp_dora_3e-3_3033st/step=3033.ckpt", (0.8, 1.0), (5, 9), 17),
    ("goa5k_r128_shampoo_k5_8088", "adapter", f"{RUNS}/goa5k_r128_shampoo_subloss_k5_2026-09-26/step=8088.ckpt", (0.5, 1.5), (4, 12), 16),
    ("fp32cmp_avp_bs4_lr1e4_ep28", "adapter", f"{RUNS}/fp32cmp_avp_t4096_bs4_lr1e4/epoch=28-step=14953.weights.ckpt", (0.4, 1.0), (4, 9), 16),   # ep20 is not on disk
]
SYN = dict(
    genre=["goa trance", "psytrance", "full-on psytrance", "progressive psytrance", "psychedelic trance", "dark psytrance", "forest psytrance", "hi-tech psytrance"],
    lead=["squelchy acid lead", "soaring synth lead", "arpeggiated lead", "hypnotic synth melody", "bubbling acid line", "sawtooth lead with delay"],
    bass=["rolling bassline", "offbeat bass", "driving galloping bass", "deep punchy bass", "pulsating sub bass"],
    perc=["tight kick and hi-hats", "intricate percussion patterns", "punchy kick, open hi-hats", "rolling percussion, shakers"],
    mood=["euphoric", "dark and hypnotic", "mystical", "energetic", "trippy", "uplifting", "ominous", "spacey"])


def prompt_pool():
    spec = [v["prompt"] for v in json.load(open(f"{RUNS}/rarity_gen_set/clip_index.json")).values() if v.get("source") == "base" and v.get("prompt")]
    kl = [p["prompt"] for p in json.load(open("/home/kim/Projects/SAO/eval/kimlong_pool.json"))]
    return sorted(set(spec)), kl


def pick_prompt(rnd, spec, kl):
    r = rnd.random()
    if r < 0.50: return rnd.choice(spec), "train_rarity"
    if r < 0.70: return rnd.choice(kl), "train_kimlong"
    bpm = rnd.randint(136, 150)
    s = SYN
    return (f"{rnd.choice(s['genre'])}, {bpm} bpm, {rnd.choice(s['lead'])}, {rnd.choice(s['bass'])}, {rnd.choice(s['perc'])}, {rnd.choice(s['mood'])}"), "synthetic"


def plan():
    rnd = random.Random(20261103); spec, kl = prompt_pool(); rows = []; i = 0
    for name, kind, ck, wr, cr, n in ARMS:
        for _ in range(n):
            p, src = pick_prompt(rnd, spec, kl)
            rows.append(dict(id=f"t{i:03d}", arm=name, kind=kind, ckpt=ck, w=round(rnd.uniform(*wr) / 0.05) * 0.05, cfg=round(rnd.uniform(*cr), 1),
                             seed=rnd.randint(1, 2**31 - 1), prompt=p, prompt_src=src)); i += 1
    return rows


def gen(model, prompt, dur, cfg, seed, **kw):
    out = model.generate(prompt=prompt, duration=dur, steps=STEPS, cfg_scale=cfg, seed=seed, batch_size=1, **kw)
    a = out[0].float().cpu().numpy()
    assert np.isfinite(a).all(), "non-finite audio"
    return a


def rms_db(a): return float(20 * np.log10(np.sqrt((a ** 2).mean()) + 1e-12))


def main():
    from stable_audio_3 import StableAudioModel
    from sa3_control.audio_io import save_audio
    os.makedirs(OUT, exist_ok=True)
    rows = plan()
    jl = f"{OUT}/cells.jsonl"; done = {json.loads(l)["id"] for l in open(jl)} if os.path.exists(jl) else set()
    if not os.path.exists(f"{OUT}/run_meta.json"):
        json.dump({"purpose": "Replacement track pool for the DJ mix: 100 tracks from six models, 30 s core + 45 s inpaint extension each side (core at 45-75 s). Owner will tag the ones that go into the mix on the eval page.",
                   "hypothesis": "tracks straight from the better checkpoints, extended by the same model and prompt, sound better than the old 16 (extended by the bridge adapter).",
                   "script": "eval/mixtape_track_pool.py", "plan": rows, "caveats": "fullft_avp_t256 ep46 and fp32cmp bs4 sweep ep20 are not on disk: ep80 and ep28 used. fp32cmp ep28 turned out to be an adapter ckpt (loaded as DoRA/LoRA). Full-FT weight = delta scaling base+w*(ft-base).",
                   "result": None, "kim_feedback": None}, open(f"{OUT}/run_meta.json", "w"), indent=1)
    arms = []
    for r in rows: 
        if r["arm"] not in arms: arms.append(r["arm"])
    only = os.environ.get("ONLY_ARM")
    for arm in arms:
        todo = [r for r in rows if r["arm"] == arm and r["id"] not in done]
        if not todo or (only and only != arm): continue
        r0 = todo[0]; t0 = time.time()
        model = StableAudioModel.from_pretrained("medium-base", device="cuda")
        base = ft = None; info = {}
        if r0["kind"] == "fullft":
            tgt = model.model.model; base = {k: v.detach().cpu().clone() for k, v in tgt.named_parameters()}
            sd = _state_dict(r0["ckpt"]); ei = ema_info(sd); use_ema = bool(ei and ei["converged"])
            info = load_fullft(model, r0["ckpt"], weights="ema" if use_ema else "online", sd=sd)
            ft = {k: v.detach().cpu().clone() for k, v in tgt.named_parameters()}; del sd
        else:
            model.load_lora([r0["ckpt"]])
        print(f"[arm] {arm} loaded in {time.time()-t0:.0f}s {info}", flush=True)
        for r in todo:
            t1 = time.time()
            if r["kind"] == "fullft":
                with torch.no_grad():
                    for k, p in model.model.model.named_parameters():
                        p.copy_((base[k].float() + r["w"] * (ft[k].float() - base[k].float())).to(p.dtype))
            else:
                model.set_lora_strength(r["w"])
            try:
                core = gen(model, r["prompt"], CORE, r["cfg"], r["seed"])
                n_core = core.shape[-1]
                W1 = CORE + EXT; z = np.zeros((core.shape[0], int(W1 * SR)), np.float32); z[:, :n_core] = core
                fwd = gen(model, r["prompt"], W1, r["cfg"], r["seed"] + 1, inpaint_audio=(SR, torch.tensor(z)),
                          inpaint_mask_start_seconds=CORE, inpaint_mask_end_seconds=W1)
                fwd = np.pad(fwd, ((0, 0), (0, max(0, int(W1 * SR) - fwd.shape[-1]))))[:, :int(W1 * SR)]
                W2 = W1 + EXT; z2 = np.zeros((core.shape[0], int(W2 * SR)), np.float32); z2[:, int(EXT * SR):] = fwd
                full = gen(model, r["prompt"], W2, r["cfg"], r["seed"] + 2, inpaint_audio=(SR, torch.tensor(z2)),
                           inpaint_mask_start_seconds=0.0, inpaint_mask_end_seconds=EXT)
                full = np.pad(full, ((0, 0), (0, max(0, int(W2 * SR) - full.shape[-1]))))[:, :int(W2 * SR)]
            except Exception as e:
                print("FAIL", r["id"], repr(e)[:200], flush=True); open(jl, "a").write(json.dumps(dict(id=r["id"], error=repr(e)[:300])) + "\n"); continue
            sec = lambda a, lo, hi: a[:, int(lo * SR):int(hi * SR)]
            save_audio(f"{OUT}/{r['id']}.wav", torch.tensor(full), SR)
            row = dict(r, dur=round(full.shape[-1] / SR, 2), rms_db=round(rms_db(full), 1), core_rms_db=round(rms_db(sec(full, EXT, EXT + CORE)), 1),
                       ext_pre_rms_db=round(rms_db(sec(full, 0, EXT)), 1), ext_post_rms_db=round(rms_db(sec(full, EXT + CORE, W2)), 1),
                       peak=round(float(np.abs(full).max()), 3), secs=round(time.time() - t1, 1))
            open(jl, "a").write(json.dumps(row) + "\n"); print(row["id"], arm, f"w{r['w']:.2f} cfg{r['cfg']}", row["rms_db"], f"{row['secs']}s", flush=True)
        del model, base, ft; import gc; gc.collect(); torch.cuda.empty_cache()
    print("POOL DONE", flush=True)


if __name__ == "__main__":
    main()
