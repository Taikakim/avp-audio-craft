"""The model database behind the SA3 inference picker.

A database of models keyed by ABSOLUTE CHECKPOINT PATH -- which is the piece that
was missing. It does NOT replace model_index.md (377 board labels / 309 models /
71 families, generated by Misc/build_model_index_page.py) or
Misc/models_index_overrides.json; it JOINS to them, so Kim's by-ear verdicts and
the extracted recipes reach the picker instead of living only in a 4358-line
markdown page.

Field precedence, deliberately:
  ckpt probe  >  run_meta.json  >  Misc/models_index_overrides.json
The checkpoint is ground truth. Some run_meta.json files are RECONSTRUCTIONS
("reconstructed_by": "...from ckpt args") and can be wrong. Overrides carry human
judgement (verdict / why) and never detected fields. Every field records where it
came from in record["provenance"].
"""
from __future__ import annotations

import hashlib
import json
import os
import time
from pathlib import Path

import ckpt_probe
from model_roots import Root, resolve_roots

SCHEMA_VERSION = 2
# DELIBERATELY NOT /tmp/sa3_explorer_ckpt_journal.json: the legacy /ckpts
# handler owns that file with an incompatible layout (roots keyed by PATH,
# no "schema" key). Sharing it makes the two caches clobber each other on
# every write, so each side would silently rescan forever.
def _journal_path() -> Path:
    """Persistent cache location (Kim 2026-08-25: "can we make that cache persistent?").

    Was /tmp, which a reboot clears -- and the first /models call afterwards re-walks
    ~2100 checkpoints across two USB spinning disks, which is the slow scan that cost us
    a morning. XDG cache dir instead; override with SA3_MODEL_DB_JOURNAL. Deliberately
    NOT the repo (it is a machine-local cache, not source) and NOT a removable drive
    (it must survive the drives being unplugged).
    """
    env = os.environ.get("SA3_MODEL_DB_JOURNAL")
    if env:
        return Path(env)
    base = os.environ.get("XDG_CACHE_HOME") or (Path.home() / ".cache")
    return Path(base) / "sa3-explorer" / "model_db.json"


JOURNAL_PATH = _journal_path()
OVERRIDES_PATH = Path(__file__).resolve().parent.parent / "Misc" / "models_index_overrides.json"
RUN_PARAMS_PATH = Path(__file__).resolve().parent.parent / "lumi" / "run_params_extracted.json"

SCAN_SUFFIXES = (".ckpt", ".safetensors", ".pt")
LOADABLE_FAMILIES = ("adapter", "fullft")
# 229 target modules x (lora_A + lora_B + magnitude) at r128 measured 666.4 MB
# fp32 => 166 M params => 0.33 GB at half. Scale linearly in rank.
#
# MEASURED CORRECTION (C, 2026-08-26): loading TWO r128 DoRAs onto a resident
# medium-base took 0.79 GB of VRAM, not 2 x 0.33 = 0.66 -- i.e. ~0.40 GB each. The
# arithmetic above counts the adapter tensors only; the extra ~0.07 GB per adapter
# is the parametrization bookkeeping the fork attaches per target module. Use the
# measured figure, because this number is what adapter_slots.SlotTable checks the
# VRAM floor against, and underestimating it is how you get an OOM instead of a
# clean refusal.
_GB_PER_RANK_HALF = 0.40 / 128.0
_FULLFT_GB_HALF = 2.8


def stable_id(path: str) -> str:
    return "MDB-" + hashlib.sha1(str(path).encode()).hexdigest()[:8]


def scan_root(root: Root) -> list[dict]:
    """Recursive scan for every checkpoint-shaped file under one root.

    Includes *.pt: control runs save riffer_final.pt / riffer_step<N>.pt and a
    glob for epoch=*.ckpt finds ZERO of them (INFERENCE-SURFACE section 2).
    """
    if not root.path or not Path(root.path).is_dir():
        return []
    base = Path(root.path)
    entries = []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for fn in filenames:
            if not fn.endswith(SCAN_SUFFIXES):
                continue
            p = Path(dirpath) / fn
            try:
                st = p.stat()
            except OSError:
                continue
            entries.append({"path": str(p), "name": str(p.relative_to(base)),
                            "mtime": st.st_mtime, "size": st.st_size,
                            "kind": p.suffix.lstrip(".")})
    entries.sort(key=lambda e: e["mtime"], reverse=True)
    return entries


def find_run_meta(path: Path, root_path: Path) -> Path | None:
    """Walk up from the checkpoint to the root looking for run_meta.json."""
    cur = path.parent
    root_path = Path(root_path).resolve()
    while True:
        cand = cur / "run_meta.json"
        if cand.is_file():
            return cand
        if cur.resolve() == root_path or cur.parent == cur:
            return None
        cur = cur.parent


def parse_run_meta(data: dict) -> dict:
    """Normalise BOTH run_meta shapes onto one field set.

    reconstructed style: {"training": {corpus, crop_frames, optimizer, lr,
        base_precision, seed, n_files, dora_rank, adapter}, purpose, status, ...}
    launch style:        {"dataset": {name}, "recipe": {adapter, rank, alpha, lr,
        frames, optimizer, precision, batch_size, epochs}, purpose, script, ...}
    """
    def _d(v):
        # Real run_meta files in the wild put a bare string where the schema
        # says object (e.g. "dataset": "goa_bigset"). Never let that raise.
        return v if isinstance(v, dict) else {}

    tr = _d(data.get("training"))
    rc = _d(data.get("recipe"))
    ds = _d(data.get("dataset"))
    if isinstance(data.get("dataset"), str):
        ds = {"name": data["dataset"]}
    out = {
        "corpus": tr.get("corpus") or ds.get("name"),
        "crop_frames": tr.get("crop_frames") or rc.get("frames"),
        "optimizer": tr.get("optimizer") or rc.get("optimizer"),
        "lr": tr.get("lr") if tr.get("lr") is not None else rc.get("lr"),
        "precision": tr.get("base_precision") or rc.get("precision"),
        "seed": tr.get("seed"),
        "n_files": tr.get("n_files"),
        "purpose": data.get("purpose"),
        "hypothesis": data.get("hypothesis"),
        "status": data.get("status"),
        "kim_feedback": data.get("kim_feedback"),
        "reconstructed": bool(data.get("reconstructed_by")),
        "slurm_job": data.get("slurm_job"),
    }
    return {k: v for k, v in out.items() if v is not None}


def _load_run_params(path=RUN_PARAMS_PATH) -> dict:
    """Launch-script recipes keyed by ARM name (= the checkpoint's parent dir).

    lumi/run_params_extracted.json is a careful per-sbatch reading (not parser
    output -- its _notes carry things like "weight_decay is INERT under
    MODE=hyperball"). It covers LUMI arms only; local sa3_lora_runs arms are out
    of its scope by construction, not missing from it.
    """
    try:
        raw = json.loads(Path(path).read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    return raw if isinstance(raw, dict) else {}


def parse_run_params(entry: dict) -> dict:
    """Map the extraction's schema onto model_db's recipe field names."""
    if not isinstance(entry, dict):
        return {}
    out = {
        "optimizer": entry.get("optimizer"),
        "lr": entry.get("lr"),
        "precision": entry.get("precision"),
        "crop_frames": entry.get("frames_T"),
        "seed": entry.get("seed"),
        "corpus": entry.get("dataset"),
        "rank": entry.get("rank"),
        "alpha": entry.get("alpha"),
        "adapter_type": entry.get("adapter_type"),
    }
    return {k: v for k, v in out.items() if v is not None}


def _load_overrides(overrides_path) -> dict:
    if overrides_path is None:
        return {}
    p = Path(overrides_path)
    if not p.is_file():
        return {}
    try:
        d = json.loads(p.read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    return {k: v for k, v in d.items() if not k.startswith("_")}


def _load_cost_gb(family: str, rank: int | None) -> float:
    if family == "fullft":
        return _FULLFT_GB_HALF
    if family == "adapter":
        return round(_GB_PER_RANK_HALF * (rank or 128), 3)
    return 0.0


def record_for(path: str, root: Root, overrides: dict,
               run_params: dict | None = None) -> dict:
    p = Path(path)
    base = Path(root.path)
    rel = p.relative_to(base)
    parts = rel.parts
    family_dir = parts[0] if len(parts) > 1 else ""
    arm = p.parent.name if p.parent != base else family_dir

    probe = ckpt_probe.probe(p)
    prov = {k: "ckpt" for k in
            ("family", "kind", "slim", "rank", "alpha", "adapter_type",
             "control_mode", "epoch", "step", "size", "mtime")
            if probe.get(k) is not None}

    rec = {
        "id": stable_id(str(p)), "path": str(p), "root_id": root.id,
        "family_dir": family_dir, "arm": arm, "label": arm,
        "family": probe["family"], "kind": probe["kind"], "slim": probe["slim"],
        "size": probe["size"], "mtime": probe["mtime"],
        "epoch": probe["epoch"], "step": probe["step"],
        "rank": probe["rank"], "alpha": probe["alpha"],
        "adapter_type": probe["adapter_type"], "control_mode": probe["control_mode"],
        "n_target_modules": probe["n_target_modules"],
        "probe_error": probe["probe_error"],
        "run_meta_path": None, "also_at": [], "_root_path": str(base),
    }

    rm_path = find_run_meta(p, base)
    if rm_path is not None:
        rec["run_meta_path"] = str(rm_path)
        try:
            raw = json.loads(rm_path.read_text())
            rm = parse_run_meta(raw) if isinstance(raw, dict) else {}
        except (OSError, json.JSONDecodeError, TypeError, AttributeError):
            rm = {}
        src = "run_meta(reconstructed)" if rm.pop("reconstructed", False) else "run_meta"
        for k, v in rm.items():
            if rec.get(k) is None:          # ckpt wins every conflict
                rec[k] = v
                prov[k] = f"{src}.{k}"

    # Launch-script recipe: below run_meta (per-run truth), above overrides.
    # Same rule as everything else here -- the checkpoint wins every conflict.
    rp = (run_params or {}).get(arm) or {}
    for k, v in parse_run_params(rp).items():
        if rec.get(k) is None:
            rec[k] = v
            prov[k] = f"run_params.{k}"

    ov = overrides.get(arm) or overrides.get(family_dir) or {}
    if ov.get("note"):
        rec["verdict"] = ov["note"]
        prov["verdict"] = "overrides"
    if ov.get("recipe"):
        rec["recipe"] = ov["recipe"]
        prov["recipe"] = "overrides"
    # Human-curated note fields WIN over run_meta: overrides is the hand-verified
    # layer. Added 2026-08-25 so a purpose mined from EXPERIMENTS.md/WORKLOG.md for
    # an arm whose run_meta never recorded one actually reaches the eval pages.
    for k in ("purpose", "hypothesis", "status", "kim_feedback"):
        if ov.get(k):
            rec[k] = ov[k]
            prov[k] = f"overrides.{k}"

    rec["loadable"] = rec["family"] in LOADABLE_FAMILIES
    rec["load_cost_gb"] = _load_cost_gb(rec["family"], rec["rank"])
    rec["provenance"] = prov
    for k in ("corpus", "crop_frames", "optimizer", "lr", "precision", "seed",
              "purpose", "status", "kim_feedback", "verdict", "recipe"):
        rec.setdefault(k, None)
    return rec


def build(roots: list[Root] | None = None,
          overrides_path: str | Path | None = OVERRIDES_PATH) -> list[dict]:
    roots = roots if roots is not None else resolve_roots()
    overrides = _load_overrides(overrides_path)
    run_params = _load_run_params()
    out: list[dict] = []
    for root in roots:
        if not root.enabled:
            continue
        for e in scan_root(root):
            out.append(record_for(e["path"], root, overrides, run_params))
    return out


def dedupe(records: list[dict], roots: list[Root] | None = None) -> list[dict]:
    """Collapse the same (arm, filename) seen under several roots.

    The Mantu lumi_runs copy is an early PARTIAL grab superseded by the UUID
    drive (ARCHITECTURE.md), so priority decides and the loser is recorded in
    the winner's "also_at".
    """
    roots = roots if roots is not None else resolve_roots()
    prio = {r.id: r.priority for r in roots}
    best: dict[tuple, dict] = {}
    for rec in records:
        key = (rec["family_dir"], rec["arm"], Path(rec["path"]).name)
        cur = best.get(key)
        if cur is None:
            best[key] = rec
        elif prio.get(rec["root_id"], 0) > prio.get(cur["root_id"], 0):
            rec["also_at"] = cur["also_at"] + [cur["path"]]
            best[key] = rec
        else:
            cur["also_at"] = cur["also_at"] + [rec["path"]]
    return list(best.values())


def _read_journal() -> dict:
    if not JOURNAL_PATH.exists():
        return {}
    try:
        j = json.loads(JOURNAL_PATH.read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    return j if j.get("schema") == SCHEMA_VERSION else {}


def _write_journal(j: dict) -> None:
    tmp = JOURNAL_PATH.with_suffix(".json.tmp")
    try:
        JOURNAL_PATH.parent.mkdir(parents=True, exist_ok=True)
        tmp.write_text(json.dumps(j))
        tmp.replace(JOURNAL_PATH)       # atomic: readers see old or new, never half
    except OSError:
        pass


def reapply_curation(rec: dict, root: "Root", overrides: dict,
                     run_params: dict | None = None) -> dict:
    """Re-join the CHEAP, hand-edited layers onto an already-probed record.

    The journal caches probe output because probing is expensive (opening every
    checkpoint on three drives takes ~an hour). Overrides and run_params are neither
    expensive nor stable -- they are edited by hand, several times a day. Baking them
    into the cache means a freshly written `purpose` does not appear until someone
    pays for a full rescan, which is how 126 mined purposes silently failed to reach
    the census on 2026-09-02: the join was correct, the cache was just older than the
    data. So the cached path re-applies them on every load. Idempotent by construction
    -- run_params only fills None, overrides always win.
    """
    path = rec.get("path")
    if not path:
        return rec
    try:
        rel = Path(path).relative_to(Path(root.path))
    except ValueError:
        return rec
    parts = rel.parts
    family_dir = parts[0] if len(parts) > 1 else ""
    arm = Path(path).parent.name if len(parts) > 1 else family_dir
    prov = rec.setdefault("provenance", {})

    rp = (run_params or {}).get(arm) or {}
    for k, v in parse_run_params(rp).items():
        if rec.get(k) is None:
            rec[k] = v
            prov[k] = f"run_params.{k}"

    ov = overrides.get(arm) or overrides.get(family_dir) or {}
    if ov.get("note"):
        rec["verdict"] = ov["note"]; prov["verdict"] = "overrides"
    if ov.get("recipe"):
        rec["recipe"] = ov["recipe"]; prov["recipe"] = "overrides"
    for k in ("purpose", "hypothesis", "status", "kim_feedback"):
        if ov.get(k):
            rec[k] = ov[k]; prov[k] = f"overrides.{k}"
    return rec


def load_or_build(root_ids: list[str] | None = None, rescan: bool = False) -> dict:
    """The server-facing entry point. Cached per root; unavailable roots serve
    their stale journal rather than failing the whole request."""
    roots = [r for r in resolve_roots() if root_ids is None or r.id in root_ids]
    journal = _read_journal()
    by_root = journal.get("roots", {})
    overrides = _load_overrides(OVERRIDES_PATH)
    run_params = _load_run_params()
    models: list[dict] = []
    stale: list[str] = []
    changed = False

    for root in roots:
        cached = by_root.get(root.id)
        if not root.enabled:
            continue
        if root.available and (rescan or cached is None):
            recs = [record_for(e["path"], root, overrides, run_params)
                    for e in scan_root(root)]
            by_root[root.id] = {"scanned_at": time.time(), "path": root.path,
                                "models": recs}
            changed = True
            models.extend(recs)
        elif cached is not None:
            if not root.available:
                stale.append(root.id)
            # Cached probe data is fine; its CURATION may be hours out of date -- re-join
            # overrides/run_params rather than serving a stale purpose (see reapply_curation).
            models.extend(reapply_curation(m, root, overrides, run_params)
                          for m in cached["models"])
        elif not root.available:
            stale.append(root.id)

    if changed:
        _write_journal({"schema": SCHEMA_VERSION, "roots": by_root})
    return {"schema": SCHEMA_VERSION,
            "roots": [r.as_dict() for r in roots],
            "models": dedupe(models, roots),
            "stale_root_ids": stale}
